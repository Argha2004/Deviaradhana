/**
 * Computes the active history fact based on 2-hour intervals of the current local time.
 * Changes automatically every 2 hours (00:00, 02:00, 04:00, 06:00, etc.).
 */
export function get2HourRotatedFact(): { fact: PujaFact; index: number; nextRotationMs: number } {
  const now = new Date();
  const currentMs = now.getTime();
  const TWO_HOURS_MS = 2 * 60 * 60 * 1000;

  // Compute 2-hour interval slot index
  const slotIndex = Math.floor(currentMs / TWO_HOURS_MS);
  const factIndex = Math.abs(slotIndex) % PUJA_HISTORY_FACTS.length;

  // Milliseconds until next 2-hour boundary
  const nextRotationMs = (slotIndex + 1) * TWO_HOURS_MS - currentMs;

  return {
    fact: PUJA_HISTORY_FACTS[factIndex],
    index: factIndex,
    nextRotationMs,
  };
}
